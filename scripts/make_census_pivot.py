#!/usr/bin/env python3
"""
make_census_pivot.py — build an .xlsx with GENUINE, refreshable Excel
PivotTables, via the LibreOffice UNO bridge.

Why this script exists (the hard-won lesson)
--------------------------------------------
If you hand-author the pivotTable / pivotCache XML yourself (or patch an
openpyxl workbook to fake a pivot), Excel rejects the file as a corrupt
"needs repair" workbook — *even when* LibreOffice and other tools open it fine.
Don't go down that road. Instead:

  1. Build the DATA-ONLY workbook with openpyxl (all sheets, formatting, and an
     empty sheet left for the pivots to render into).
  2. Let LibreOffice generate the native PivotTables (DataPilot tables) through
     the python-UNO bridge, and write the final .xlsx with the
     "Calc MS Excel 2007 XML" filter.

LibreOffice's writer produces Excel-conformant, refreshable pivots. It labels
the value column "Count - <field>", the row header with the field name, and the
grand total "Total Result" — that labeling is expected and fine.

This is a genericized demo (a generic headcount roster: count IDs by Department,
and by Country). Swap in your own data source and pivot fields.

Requirements
------------
  - openpyxl          (pip install openpyxl)
  - LibreOffice with the python-UNO bridge:
      Debian/Ubuntu:  apt-get install libreoffice-calc python3-uno
      macOS (brew):   brew install --cask libreoffice   (uses LO's bundled python)
    `soffice` must be on PATH (or pass --soffice).

Usage
-----
  # build data workbook + add live pivots in one go:
  python make_census_pivot.py sample_data/roster_sample.csv -o roster_with_pivots.xlsx

  # just the data workbook, no pivots (no LibreOffice needed):
  python make_census_pivot.py sample_data/roster_sample.csv -o roster.xlsx --data-only
"""
from __future__ import annotations

import argparse
import csv
import os
import subprocess
import sys
import time
from typing import Dict, List, NamedTuple, Optional

# ---- configuration you'd customize per report -------------------------------
DATA_SHEET = "Roster"
PIVOT_SHEET = "Pivot"
COUNT_FIELD = "Employee Id"   # the field the pivots COUNT


class Pivot(NamedTuple):
    name: str          # pivot table name (must be unique in the sheet)
    row_field: str     # the field placed on rows
    anchor: str        # top-left cell on PIVOT_SHEET, e.g. "A3"


PIVOTS: List[Pivot] = [
    Pivot("ByDepartment", "Department", "A3"),
    Pivot("ByCountry", "Country", "D3"),
]
# -----------------------------------------------------------------------------


# ========================= Step 1: data-only workbook ========================
def build_data_workbook(csv_path: str, out_path: str) -> List[str]:
    """Write the data-only workbook with openpyxl. Returns the header order."""
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill
    from openpyxl.utils import get_column_letter

    with open(csv_path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        raise SystemExit(f"no rows in {csv_path}")
    headers = list(rows[0].keys())
    for needed in (COUNT_FIELD, *[p.row_field for p in PIVOTS]):
        if needed not in headers:
            raise SystemExit(f"source is missing required column: {needed!r}")

    wb = Workbook()
    ws = wb.active
    ws.title = DATA_SHEET

    header_font = Font(bold=True, color="FF666666")
    header_fill = PatternFill("solid", fgColor="FFEDE7F6")
    ws.append(headers)
    for col, _ in enumerate(headers, start=1):
        c = ws.cell(row=1, column=col)
        c.font = header_font
        c.fill = header_fill
    for r in rows:
        ws.append([r.get(h, "") for h in headers])

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows) + 1}"
    for col, h in enumerate(headers, start=1):
        width = max(len(h), *(len(str(r.get(h, ""))) for r in rows)) + 2
        ws.column_dimensions[get_column_letter(col)].width = min(width, 40)

    # Empty sheet for the pivots to render into (title optional).
    wb.create_sheet(PIVOT_SHEET)["A1"] = "Headcount pivots (generated by LibreOffice)"

    wb.save(out_path)
    print(f"[1/2] data workbook written: {out_path}  "
          f"({len(rows)} rows, {len(headers)} cols)")
    return headers


# ========================= Step 2: LibreOffice pivots ========================
def _col_index(headers: List[str], name: str) -> int:
    return headers.index(name)  # 0-based, matches UNO column index


def add_pivots_with_libreoffice(xlsx_path: str, headers: List[str],
                                n_rows: int, soffice: str = "soffice",
                                port: int = 2002) -> None:
    """Open the workbook in headless LibreOffice and insert native DataPilots."""
    try:
        import uno  # noqa: F401  (provided by python3-uno / LO bundled python)
        from com.sun.star.beans import PropertyValue
        from com.sun.star.sheet.DataPilotFieldOrientation import (
            ROW, DATA, HIDDEN,
        )
        from com.sun.star.sheet.GeneralFunction import COUNT
        from com.sun.star.table import CellRangeAddress
    except ImportError as exc:  # pragma: no cover - env dependent
        raise SystemExit(
            "python-UNO is not importable in this interpreter.\n"
            "Run with LibreOffice's bundled python, or install python3-uno, or\n"
            "use --data-only to skip the pivots.\n"
            f"(import error: {exc})"
        )

    profile = os.path.abspath("./.lo_profile_tmp")
    proc = subprocess.Popen(
        [soffice, "--headless", "--invisible", "--nologo", "--norestore",
         f"--accept=socket,host=localhost,port={port};urp;",
         f"-env:UserInstallation=file://{profile}"],
    )
    ctx = _connect(port, timeout=60)
    try:
        smgr = ctx.ServiceManager
        desktop = smgr.createInstanceWithContext(
            "com.sun.star.frame.Desktop", ctx)
        url = _path_to_url(os.path.abspath(xlsx_path))
        hidden = _prop("Hidden", True)
        doc = desktop.loadComponentFromURL(url, "_blank", 0, (hidden,))
        try:
            sheets = doc.Sheets
            data_sheet = sheets.getByName(DATA_SHEET)
            pivot_sheet = sheets.getByName(PIVOT_SHEET)
            tables = pivot_sheet.DataPilotTables

            # source range: whole data table including header row
            src = CellRangeAddress()
            src.Sheet = sheets.getByName(DATA_SHEET).RangeAddress.Sheet
            src.StartColumn = 0
            src.StartRow = 0
            src.EndColumn = len(headers) - 1
            src.EndRow = n_rows  # header + data rows (0-based inclusive)

            count_idx = _col_index(headers, COUNT_FIELD)

            for piv in PIVOTS:
                desc = tables.createDataPilotDescriptor()
                desc.SourceRange = src
                fields = desc.DataPilotFields
                row_idx = _col_index(headers, piv.row_field)
                for i in range(len(headers)):
                    orient = HIDDEN
                    f = fields.getByIndex(i)
                    if i == row_idx:
                        f.Orientation = ROW
                    elif i == count_idx:
                        f.Orientation = DATA
                        f.Function = COUNT
                    else:
                        f.Orientation = orient
                anchor = pivot_sheet.getCellRangeByName(piv.anchor).CellAddress
                tables.insertNewByName(piv.name, anchor, desc)

            # store as Excel 2007 xlsx (refreshable pivots)
            out = _prop("FilterName", "Calc MS Excel 2007 XML")
            doc.storeToURL(url, (out,))
            print(f"[2/2] pivots inserted + saved: {xlsx_path}  "
                  f"({', '.join(p.name for p in PIVOTS)})")
        finally:
            doc.close(False)
    finally:
        try:
            desktop.terminate()
        except Exception:
            pass
        try:
            proc.terminate()
            proc.wait(timeout=15)
        except Exception:
            proc.kill()


def _connect(port: int, timeout: int = 60):
    import uno
    local = uno.getComponentContext()
    resolver = local.ServiceManager.createInstanceWithContext(
        "com.sun.star.bridge.UnoUrlResolver", local)
    deadline = time.time() + timeout
    last = None
    while time.time() < deadline:
        try:
            return resolver.resolve(
                f"uno:socket,host=localhost,port={port};urp;"
                "StarOffice.ComponentContext")
        except Exception as exc:  # bridge not up yet
            last = exc
            time.sleep(1)
    raise SystemExit(f"could not connect to LibreOffice on port {port}: {last}")


def _prop(name: str, value):
    from com.sun.star.beans import PropertyValue
    p = PropertyValue()
    p.Name = name
    p.Value = value
    return p


def _path_to_url(path: str) -> str:
    import uno
    return uno.systemPathToFileUrl(path)


# ================================== CLI ======================================
def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv", help="source roster CSV")
    ap.add_argument("-o", "--out", default="roster_with_pivots.xlsx",
                    help="output .xlsx path")
    ap.add_argument("--data-only", action="store_true",
                    help="build the data workbook only; skip LibreOffice pivots")
    ap.add_argument("--soffice", default="soffice", help="path to soffice binary")
    ap.add_argument("--port", type=int, default=2002, help="UNO socket port")
    args = ap.parse_args(argv)

    headers = build_data_workbook(args.csv, args.out)
    if args.data_only:
        print("done (data-only).")
        return 0

    n_data = sum(1 for _ in open(args.csv, encoding="utf-8")) - 1
    add_pivots_with_libreoffice(args.out, headers, n_rows=n_data,
                                soffice=args.soffice, port=args.port)
    print("done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
